def build(LISTS):
    """The checks, in the shape lists.write_check reads: items in a fixed mixed order, then the invented words."""
    by = {L["slug"]: L for L in LISTS}
    out, bad = {}, []
    for slug, (feature, look, taught, transfer, limit, control, invented) in DATA.items():
        L = by[slug]
        sent = {w: s for w, _, s in L["words"]}
        practised = {w for w, _, _ in L["words"]} | {a for _, a in L["check"]}
        bad += [(slug, w) for w, *_ in transfer + limit + control if w in practised]   # a word the list practises tests only the list
        bad += [(slug, w, "not taught") for w in taught if w not in sent]
        groups = {"taught": [(w, "taught", sent[w], look) for w in taught],
                  "transfer": [(w, "transfer", s, f or look) for w, s, f in transfer],
                  "limit": [(w, "limit", s, f) for w, s, f in limit],
                  "control": [(w, "control", s, "") for w, s in control]}
        items, order = [], ["transfer", "control", "taught", "limit"]
        while any(groups.values()):
            for g in order:
                if groups[g]: items.append(groups[g].pop(0))
        title = L["title"]
        n = len(items) + len(invented)
        if slug == "this-that-then":
            no_inv = " This list has no made-up words: a closed set takes no new words."
        else:
            no_inv = " This list has no made-up words: its convention doesn&rsquo;t predict one spelling for a word nobody has seen."
        out[slug] = {"no_inv": no_inv, "title": title, "feature": feature, "items": items, "invented": invented,
                     "desc": f"A check for the spelling list '{html.unescape(title)}': {n} words to dictate, before and after the lesson, with a scoring key."}
    assert not bad, bad
    return out
